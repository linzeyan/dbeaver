//! What each database calls a keyword.
//!
//! A common vocabulary and five short deltas, rather than six lists. That is
//! most of what makes this table-driven: what is particular to a dialect is the
//! only thing written down under its name, so the difference between two of
//! them is readable at a glance — eight words for DuckDB, eighteen for SQL
//! Server.
//!
//! The lists are read out of the databases rather than remembered, which is the
//! only way they stay true across a version bump. Each table records the query
//! that produced it. Two needed a program instead of a query and those are kept
//! as `crates/drivers/duckdb/examples/duckdb-keywords.rs` and its SQLite
//! counterpart, so the tables can
//! be regenerated rather than patched by hand.
//!
//! Every list is sorted, and that is load-bearing rather than tidy: lookup is a
//! binary search over a static slice, so an entry in the wrong place is simply
//! never found. The test at the bottom is what keeps it true.

/// The vocabulary of SQL itself, as every one of these dialects reads it.
///
/// Sourced from `SELECT word, catcode FROM pg_get_keywords()` on PostgreSQL
/// 17.10 — the table Appendix C of the manual is generated from — and then
/// judged, because a keyword table and a highlighter's word list are not the
/// same thing. Every reserved word is here; painting one can never surprise
/// anybody, since the server will not accept it as a bare column name either.
///
/// The unreserved bucket is where the judgement is. It cannot be taken whole:
/// it holds 327 words including `name`, `value`, `level` and `year`, which are
/// unreserved precisely because they are ordinary column names, and an editor
/// that paints `SELECT name, value FROM config` as three keywords is worse than
/// one that paints nothing. Nor can it be dropped: `insert`, `update`, `delete`
/// and `set` are all unreserved, and an editor that does not colour `INSERT` is
/// not colouring SQL. So what is taken is the unreserved words that name a
/// statement, name something a statement acts on, or introduce a clause.
///
/// The cost of that line is real and accepted: a column genuinely called `key`
/// or `type` gets painted, which is a cosmetic surprise on a rare name, against
/// `PRIMARY KEY` and `CREATE TYPE` going unpainted every time they occur.
///
/// PostgreSQL therefore has no table of its own below. It is this one.
