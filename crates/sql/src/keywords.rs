/// Whether `word`, already folded to lower case, is one of `list`.
pub(crate) fn contains(list: &[&str], word: &str) -> bool {
    list.binary_search(&word).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    const TABLES: &[(&str, &[&str])] = &[
        ("COMMON", COMMON),
        ("MYSQL", MYSQL),
        ("MSSQL", MSSQL),
        ("SQLITE", SQLITE),
        ("DUCKDB", DUCKDB),
        ("CLICKHOUSE", CLICKHOUSE),
    ];

    /// Every table is sorted and holds no word twice, because lookup is a
    /// binary search over it.
    ///
    /// The failure this prevents is silent. An entry in the wrong place is not
    /// reported by anything; it simply stops being a keyword, and one word is
    /// left grey in a screen of colour.
    #[test]
    fn every_table_is_sorted_because_lookup_assumes_it() {
        for (name, list) in TABLES {
            let mut sorted = list.to_vec();
            sorted.sort_unstable();
            assert_eq!(*list, sorted.as_slice(), "{name} is out of order");
            assert!(
                list.windows(2).all(|w| w[0] != w[1]),
                "{name} repeats a word"
            );
        }
    }

    /// A dialect's table holds only what is particular to it.
    ///
    /// Not tidiness: a word in both tables is a word whose removal from one of
    /// them changes nothing, so the next person to edit these cannot tell what
    /// is load-bearing.
    #[test]
    fn a_dialect_adds_only_what_the_common_table_lacks() {
        for (name, list) in &TABLES[1..] {
            for word in *list {
                assert!(
                    !contains(COMMON, word),
                    "{name} repeats the common word {word:?}"
                );
            }
        }
    }
}
